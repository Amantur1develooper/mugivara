# -*- coding: utf-8 -*-
"""Отправка уведомлений без очереди.

Все уведомления в Telegram раньше уходили через Celery — `task.delay(...)`.
Беда в том, что `delay` считается успешным, как только задача положена в
очередь: если фоновый процесс Celery не запущен, задача лежит там вечно и
никто об этом не узнаёт. Снаружи это выглядит так, будто бот сломался —
хотя бот отвечает на «/id» и чат настроен верно.

Поэтому уведомления отправляются сразу, в отдельном потоке: клиент не
ждёт ответа Telegram, а сообщение не зависит от того, запущена ли очередь.
"""
import logging
import threading

from django.db import connections

log = logging.getLogger(__name__)


def send_now(task, *args, **kwargs):
    """Выполняет задачу уведомления в фоновом потоке, минуя очередь."""

    def runner():
        try:
            # Зовём саму функцию: механика повторов Celery вне воркера
            # всё равно не работает, а ошибку мы запишем в лог сами.
            task(*args, **kwargs)
        except Exception as e:
            log.exception("уведомление %s не отправилось: %s",
                          getattr(task, "name", task), e)
        finally:
            # Поток берёт своё соединение с базой — его нужно закрыть,
            # иначе на сервере копятся висящие подключения.
            connections.close_all()

    threading.Thread(target=runner, daemon=True).start()
